// Precompiles the vendored report and suite schemas into standalone validators so the page needs no
// runtime code generation and can keep a CSP without 'unsafe-eval'.
// Usage: node scripts/gen-validator.mjs [--check]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const targets = [
  ["vendor/chargeguard-runner/report.v1.schema.json", "src/generated/validateReport.js"],
  ["vendor/chargeguard-runner/suite.v1.schema.json", "src/generated/validateSuite.js"],
];
mkdirSync("src/generated", { recursive: true });
let stale = false;
for (const [schemaPath, out] of targets) {
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  const ajv = new Ajv2020({ strict: false, validateFormats: false, allErrors: true, code: { source: true, esm: true } });
  const validate = ajv.compile(schema);
  const code = `// @ts-nocheck\n// Generated by scripts/gen-validator.mjs from ${schemaPath}. Do not edit.\n` + standaloneCode(ajv, validate);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(out, "utf8");
    } catch {
      /* missing counts as stale */
    }
    if (current !== code) {
      console.error(`${out} is out of date; run pnpm gen`);
      stale = true;
    }
  } else {
    writeFileSync(out, code);
    console.log(`wrote ${out}`);
  }
}
if (stale) process.exit(1);
